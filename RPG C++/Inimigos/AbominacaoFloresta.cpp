// --- PROCESSAMENTO DE DANO  ---
void AbominacaoFloresta::aoCausarDano(SistemaPersonagem* atacante, SistemaPersonagem* alvo, int danoCausado) 
{
    int vidaMax = atacante->obterVidaMaxima();
    int vidaAtual = atacante->obterVida();

    if (vidaAtual < (vidaMax * 0.40))
    {
        curandoAtivamente = true;
    }
    else
    {
        curandoAtivamente = false;
    }

    if (curandoAtivamente)
    {
        int cura = danoCausado;
        if (cura > 0)
        {
            int vidaFaltantePara60 = static_cast<int>(vidaMax * 0.60) - vidaAtual;
            if (vidaFaltantePara60 < 0) vidaFaltantePara60 = 0;

            if (cura > vidaFaltantePara60)
            {
                cura = vidaFaltantePara60;
            }

            if (cura > 0)
            {
                atacante->modificarVida(cura);
                // A mensagem na UI foi removida para priorizar o combate limpo
                // std::string msg = Aparencia::margemCombate() + Aparencia::cor(Cor::VERDE) + "[PASSIVA]: Raizes Parasitas! A Abominacao absorveu " + std::to_string(cura) + " de HP!" + Aparencia::cor(Cor::RESET) + "\n";
                // TelaCombate::adicionarMensagemFixa(msg);
                Aparencia::registrarLogBatalha(Aparencia::cor(Cor::VERDE) + "[PASSIVA]: Raizes Parasitas! A Abominacao absorveu " + std::to_string(cura) + " de HP!" + Aparencia::cor(Cor::RESET));
            }
        }
        if (atacante->obterVida() >= (vidaMax * 0.60))
        {
            curandoAtivamente = false;
        }
    }
}

