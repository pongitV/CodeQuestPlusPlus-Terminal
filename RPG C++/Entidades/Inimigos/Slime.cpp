void Slime::realizarDrops(Personagem* inimigo, Personagem* jogadorAtual, std::vector<std::string>& itensObtidos, int& ouroTotal, int& xpTotal)
{
    Drops::relatarEProcessarXpOuro(jogadorAtual, 35, 15, ouroTotal, xpTotal);

    Drops::darEProcessarItem(jogadorAtual, ItemID::GosmaAcida, 3, itensObtidos);
    Drops::darEProcessarItem(jogadorAtual, ItemID::NucleoPegajoso, 1, itensObtidos, 30);
}

