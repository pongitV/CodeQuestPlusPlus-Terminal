// [PT-BR] --- BESTIARIO E DROPS ---
// [EN-US] --- BESTIARY AND DROPS ---
InfoBestiary Goblin::getInfoBestiary() const {
    return {
        "Vila Inicial", 
        "Arredores",
        "Pequenas criaturas verdes e astutas que costumam viver em bandos perto de vilarejos.",
        "Goblins adoram itens brilhantes e guardam dentes como trofeus.",
        {ItemFactory::getNameFromID(ItemID::ToothGoblin), ItemFactory::getNameFromID(ItemID::DaggerStone), "Ouro"},
        1
    };
}

void Goblin::performDrops(Character* enemy, Character* currentPlayer, std::vector<std::string>& obtainedItems, int& totalGold, int& totalXp)
{
    Drops::reportAndProcessXpGold(currentPlayer, 40, 20, totalGold, totalXp);

    if (enemy->getWeapons() && enemy->getWeapons()->getItemName() == "Adaga artesanal de pedra") {
        Drops::giveAndProcessItem(currentPlayer, ItemID::DaggerStone, 1, obtainedItems, 65);
    }
    
    Drops::giveAndProcessItem(currentPlayer, ItemID::ToothGoblin, RandomGenerator::getInteger(4, 8), obtainedItems);
}







