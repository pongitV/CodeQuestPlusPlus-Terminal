InfoBestiary Slime::getInfoBestiary() const {
    return {
        "Floresta", 
        "Superficie",
        "Massas gelatinosas que absorvem tudo o que tocam.",
        "Slimes podem digerir materiais em dias, mas detestam sal.",
        {ItemFactory::getNameFromID(ItemID::SlimeAcid), ItemFactory::getNameFromID(ItemID::NucleusSticky), "Ouro"},
        2
    };
}

void Slime::performDrops(Character* enemy, Character* currentPlayer, std::vector<std::string>& obtainedItems, int& totalGold, int& totalXp)
{
    Drops::reportAndProcessXpGold(currentPlayer, 35, 15, totalGold, totalXp);

    Drops::giveAndProcessItem(currentPlayer, ItemID::SlimeAcid, 3, obtainedItems);
    Drops::giveAndProcessItem(currentPlayer, ItemID::NucleusSticky, 1, obtainedItems, 30);
}

// [PT-BR] --- PROCESSAMENTO DE DANO ---
// [EN-US] --- DAMAGE PROCESSING ---
void Slime::onCausingDamage(Character* attacker, Character* target, int damageCaused) {
    if (RandomGenerator::rollChance(15)) {
        if (!target->ownsEffect(EffectID::Slowness)) {
            target->addEffect(std::make_unique<SlownessEffect>(3));
            /*
             * A mensagem na UI foi removida para priorizar o combate limpo
             * std::string msg = CombatScreen::combatMargin() + Appearance::color(Color::MAGENTA) + ">> [PASSIVA SLIME]: Uma gosma esverdeada grudou e deixou " + alvo->getName() + " mais lento!" + Appearance::color(Color::RESET) + "\n";
             * CombatScreen::addFixedMessage(msg);
             */
            Appearance::registerBattleLog(DialogueFunctions::formatSkillMsg("Uma gosma esverdeada grudou e deixou " + target->getName() + " mais lento!", Color::MAGENTA));
        }
    }
}
