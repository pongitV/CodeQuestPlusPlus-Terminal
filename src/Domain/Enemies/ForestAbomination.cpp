// --- PROCESSAMENTO DE DANO  ---
void ForestAbomination::aoCauseDamage(Character* attacker, Character* target, int damageCaused) 
{
    int lifeMax = attacker->getMaxHealth();
    int lifeCurrent = attacker->getHealth();

    if (lifeCurrent < (lifeMax * 0.40))
    {
        healingActively = true;
    }
    else
    {
        healingActively = false;
    }

    if (healingActively)
    {
        int healing = damageCaused;
        if (healing > 0)
        {
            int lifeMissingFor60 = static_cast<int>(lifeMax * 0.60) - lifeCurrent;
            if (lifeMissingFor60 < 0) lifeMissingFor60 = 0;

            if (healing > lifeMissingFor60)
            {
                healing = lifeMissingFor60;
            }

            if (healing > 0)
            {
                attacker->modifyHealth(healing);
                /*
                 * A mensagem na UI foi removida para priorizar o combate limpo
                 * std::string msg = TelaCombate::margemCombate() + Aparencia::cor(Cor::VERDE) + "[PASSIVA]: Raizes Parasitas! A Abominacao absorveu " + std::to_string(cura) + " de HP!" + Aparencia::cor(Cor::RESET) + "\n";
                 * TelaCombate::adicionarMensagemFixa(msg);
                 */
                Appearance::registerBattleLog(DialogueFunctions::formatSkillMsg("Raizes Parasitas! A Abominacao absorveu " + std::to_string(healing) + " de HP!", Color::GREEN));
            }
        }
        if (attacker->getHealth() >= (lifeMax * 0.60))
        {
            healingActively = false;
        }
    }
}

